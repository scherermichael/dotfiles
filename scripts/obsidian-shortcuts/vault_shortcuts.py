def check_gtd_json(vault: Vault) -> None:
    config = vault.root / ".gtd.json"
    try:
        inbox = json.loads(config.read_text(encoding="utf-8")).get("inbox")
    except (OSError, ValueError):
        return
    if inbox and inbox != vault.inbox:
        print(f"WARNING: {vault.label}: .gtd.json says inbox '{inbox}', the vault list '{vault.inbox}'")


def install(vaults: list[Vault], retired: list[str], dry_run: bool) -> int:
    present = lambda v: v.root.is_dir()
    for vault in vaults:
        if present(vault):
            check_gtd_json(vault)
    wanted = wanted_shortcuts(vaults, HOME, ICLOUD_OBSIDIAN.is_dir())
    names = {name for name, *_ in wanted}
    installed = list_shortcuts()
    relevant = [(n, sid) for n, sid in installed if is_ours(n, names, retired)]
    folders = {sid: folder_of(sid) for _, sid in relevant}
    # Every shortcut that carries one of our names (an old hotkey shortcut's
    # included), has carried one, or was parked by us. Parked ones are taken
    # out of every menu and off their key.
    ours = {sid for _, sid in relevant} | {sid for sid, f in folders.items() if f == REPLACED_FOLDER}
    parked = {sid for sid, f in folders.items() if f == REPLACED_FOLDER}
    failures = 0
    current_ids: dict[str, str] = {}

    with tempfile.TemporaryDirectory() as tmp:
        workdir = Path(tmp)
        token = workdir / "token.txt"
        token.write_text(TOKEN, encoding="utf-8")
        for name, wf, build in wanted:
            ids = [sid for n, sid in installed if n == name]
            current = None
            for sid in ids:
                if folders.get(sid) == MANAGED_FOLDER and query_build(sid, token) == build:
                    current = sid
                    break
            stale = [sid for sid in ids if sid != current]
            if current:
                print(f"{name}: up to date ({build})")
            elif dry_run:
                print(f"{name}: would import build {build}" + (f", replacing {len(stale)}" if stale else ""))
            else:
                print(f"{name}: importing build {build}")
                try:
                    current = import_shortcut(wf, name, workdir)
                except RuntimeError as error:
                    print(f"FAILED: {error}", file=sys.stderr)
                    failures += 1
                    continue
                move_to_folder(current, MANAGED_FOLDER)
            for sid in stale:
                print(f"  {'would park' if dry_run else 'parking'} the previous copy {sid} in '{REPLACED_FOLDER}'")
                if not dry_run:
                    move_to_folder(sid, REPLACED_FOLDER)
                parked.add(sid)
            if current:
                current_ids[name] = current

    for name, sid in not_needed(relevant, names, folders):
        print(f"{name}: not needed on this Mac, {'would park' if dry_run else 'parking'} {sid} in '{REPLACED_FOLDER}'")
        if not dry_run:
            move_to_folder(sid, REPLACED_FOLDER)
        parked.add(sid)

    for name in retired:
        for n, sid in installed:
            if n == name and folders.get(sid) != REPLACED_FOLDER:
                print(f"{name}: retired, {'would park' if dry_run else 'parking'} {sid} in '{REPLACED_FOLDER}'")
                if not dry_run:
                    move_to_folder(sid, REPLACED_FOLDER)
                parked.add(sid)

    domain, status = pbs_status()
    existing = {sid for _, sid in list_shortcuts()}
    wanted_services = services_wanted(current_ids)
    merged, warnings = merge_services(status, wanted_services, parked & existing, existing, ours)
    for warning in warnings:
        print(f"WARNING: {warning}")
    changed = lambda sid: merged.get(SERVICE_ENTRY.format(id=sid)) != status.get(SERVICE_ENTRY.format(id=sid))
    changes = []
    finder = FILE_PICKER in current_ids and changed(current_ids[FILE_PICKER])
    if finder:
        changes.append(f"Finder -> {current_ids[FILE_PICKER]}")
    hidden = [sid for sid in parked & existing if changed(sid)]
    if hidden:
        changes.append(f"{len(hidden)} parked cop{'y' if len(hidden) == 1 else 'ies'} hidden")
    if merged != status:
        print(f"Services settings{' would change' if dry_run else ''}: " + (", ".join(changes) or "tidied"))
        if not dry_run:
            write_pbs(domain, merged)
            if finder:
                # Finder reads its Quick Actions when it starts; without a
                # relaunch the new copy stays invisible until the next login.
                # Like defaults.sh does with the Dock.
                print("relaunching Finder, so it shows the Quick Action")
                run("killall", "Finder", check=False)
    else:
        print("Services settings: unchanged")
    if not install_note_helper(vaults, present, dry_run):
        failures += 1
    return 1 if failures else 0


def build_only(vaults: list[Vault], out: Path) -> int:
    """Write every shortcut as an XML plist and the data vault-note would be
    built with, for review; touches nothing else."""
    out.mkdir(parents=True, exist_ok=True)
    for name, wf, build in wanted_shortcuts(vaults, HOME, ICLOUD_OBSIDIAN.is_dir()):
        (out / f"{name}.plist").write_bytes(plistlib.dumps(wf, fmt=plistlib.FMT_XML))
        print(f"{name}: build {build}")
    config = note_helper_config(vaults, lambda v: v.root.is_dir())
    (out / "vault-note.json").write_text(json.dumps(config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    labels = ", ".join(v["label"] for v in config["vaults"])
    print("vault-note: built in would be " + (labels or "no vault on this Mac"))
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", nargs="?", default="install", choices=("install", "status", "build"))
    parser.add_argument("--vault", nargs=4, action="append", default=[],
                        metavar=("LABEL", "ROOT", "INBOX", "PHONE_ROOT"))
    parser.add_argument("--retire", action="append", default=[], metavar="NAME")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--out", type=Path, help="for build: where the plists go")
    args = parser.parse_args(argv)
    vaults = [Vault(label, Path(root), inbox, phone) for label, root, inbox, phone in args.vault]
    if not vaults:
        print("No vaults given; nothing to do.")
        return 0
    if args.command == "build":
        if not args.out:
            parser.error("build needs --out")
        return build_only(vaults, args.out)
    return install(vaults, args.retire, dry_run=args.dry_run or args.command == "status")


if __name__ == "__main__":
    sys.exit(main())
