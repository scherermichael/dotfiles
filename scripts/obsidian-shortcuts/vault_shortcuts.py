# The hotkey shortcuts of earlier versions, "Add to Vault Inbox (<label>)", one
# per vault. The Mac's quick note is vault-note now; these are parked wherever
# the managed folder still holds one.
FIXED_NAME = re.compile(r"^Add to Vault Inbox \(.+\)$")


def is_ours(name: str, wanted: set[str], retired: list[str]) -> bool:
    """Whether install looks at a shortcut: one of the names it wants, or has
    ever made, also as an import's numbered copy ("... 2"), or a retired one.

    The pickers count whether this Mac wants them or not: a note picker no
    longer wanted has to be seen before it can be parked.
    """
    base = re.sub(r" \d+$", "", name)
    return (base in wanted or base in (NOTE_PICKER, FILE_PICKER) or bool(FIXED_NAME.match(base))
            or name in retired)


def not_needed(shortcuts: list[tuple[str, str]], wanted: set[str], folders: dict[str, str]):
    """(name, ID) of our shortcuts in the managed folder this Mac does not
    want: every old hotkey shortcut, and the note picker on a Mac whose vaults
    the iPhone cannot reach.

    Parked, not kept: Macs sharing a library share their vaults too, so no
    other Mac still wants them. Only the managed folder counts, as for the
    build query: a shortcut of that name elsewhere may be a hand-made one.
    """
    ours = lambda n: FIXED_NAME.match(n) or n in (NOTE_PICKER, FILE_PICKER)
    return [(n, sid) for n, sid in shortcuts
            if ours(n) and n not in wanted and folders.get(sid) == MANAGED_FOLDER]


def choose_vault(sc: Shortcut, vaults: list[Vault], home: Path, icloud_on_mac: bool) -> dict:
    """Offer the vaults whose inbox this device can reach, and set "vault".

    Every vault of the config is in the build, so the build is the same on
    every Mac sharing a Shortcuts library; which of them are offered is decided
    when it runs. With a single one the list is skipped.

    The one exception is a Mac without Obsidian's iCloud folder (the work Mac,
    whose iCloud is restricted). There the Mac branch leaves the iCloud vaults
    out: below a missing root a lookup does not come back empty, it stops the
    shortcut. Such a Mac has its own library, so its different build competes
    with no other copy.
    """
    device = sc.device_model()

    def offer_if_reachable(vault: Vault, root: str, inbox: str):
        found = sc.get_file(root, f"{inbox}/_Inbox.md")
        with sc.if_(found, HAS_VALUE):
            # A second hit means the list has to be shown. Counting would do,
            # but "has any value" is the only comparison proven to work here.
            with sc.if_(variable("vaults"), HAS_VALUE):
                sc.set_variable("several", sc.get_text("yes"))
            sc.append_variable("vaults", sc.get_text(vault.label))

    with sc.if_(device, CONTAINS, "Mac") as branch:
        for vault in vaults:
            root, inbox = mac_inbox(vault, home)
            if root != "icloud" or icloud_on_mac:
                offer_if_reachable(vault, root, inbox)
        branch.otherwise()
        for vault in vaults:
            phone = phone_inbox(vault, home)
            if phone:
                offer_if_reachable(vault, *phone)
    with sc.if_(variable("vaults"), HAS_VALUE) as branch:
        branch.otherwise()
        sc.notify(text("No vault inbox is reachable on this device."))
        sc.stop()
    with sc.if_(variable("several"), HAS_VALUE) as branch:
        sc.set_variable("vault", sc.choose_from_list(variable("vaults"), "Vault:"))
        branch.otherwise()
        sc.set_variable("vault", sc.first_item(variable("vaults")))
    return device


def for_each_location(sc: Shortcut, vaults: list[Vault], device: dict, home: Path, body) -> None:
    """Run body(vault, root kind, inbox path) in the branch of the chosen vault
    on this kind of device. Folders in Shortcuts are fixed per step, hence one
    branch per vault and device rather than a variable path."""
    for vault in vaults:
        with sc.if_(variable("vault"), IS, vault.label):
            with sc.if_(device, CONTAINS, "Mac") as branch:
                body(vault, *mac_inbox(vault, home))
                phone = phone_inbox(vault, home)
                if phone:
                    branch.otherwise()
                    body(vault, *phone)


def note_picker(vaults: list[Vault], home: Path = HOME, icloud_on_mac: bool = True) -> dict:
    """The iPhone's share sheet, and free input from a home-screen icon. It
    shows in the Mac's share menu too, whose entries are the same setting."""
    sc = Shortcut(NOTE_PICKER)
    sc.comment(GENERATED)
    sc.version_check()
    device = choose_vault(sc, vaults, home, icloud_on_mac)

    def write(vault: Vault):
        def to_inbox(entry: dict):
            with sc.if_(device, CONTAINS, "Mac") as branch:
                root, inbox = mac_inbox(vault, home)
                sc.append_file(root, f"{inbox}/_Inbox.md", entry)
                phone = phone_inbox(vault, home)
                if phone:
                    branch.otherwise()
                    sc.append_file(phone[0], f"{phone[1]}/_Inbox.md", entry)
        return to_inbox

    # What the dialog starts with. A shared web page taken as text would be the
    # whole page; it becomes a bookmark instead: "Web - <title>" as the task,
    # as the capture tool names web pages, and the address below it. With text
    # selected, Safari hands over only the text, and no address comes with it.
    sc.set_variable("prefill", sc.get_text(shortcut_input(as_text=True)))
    with sc.unless_empty(page_url(shortcut_input())):
        # A "#" in a page title would turn into a tag; the capture tool
        # defuses it the same way.
        title = sc.replace(item_name(shortcut_input()), DEFUSE_TAG, "＃")
        sc.set_variable("prefill", sc.get_text("Web - ", title, "\n", page_url(shortcut_input())))

    # One dialog per vault, each with its name in the title: with two vaults
    # on a device, the title is what shows where the note will land.
    for vault in vaults:
        with sc.if_(variable("vault"), IS, vault.label):
            note = sc.ask(f"Add to {vault.label} inbox:", text(variable("prefill")))
            sc.note(note, write(vault))
    # Not in Services: selected text on the Mac is the capture tool's business,
    # and the quick note there is vault-note.
    return sc.workflow(TEXT_INPUT + ["WFURLContentItem", "WFSafariWebPageContentItem"],
                       ["ActionExtension", "WFWorkflowTypeShowInSearch"])


def file_picker(vaults: list[Vault], home: Path = HOME, icloud_on_mac: bool = True) -> dict:
    """Files into the inbox folder, each with a task linking to it.

    PDFs and images stay what they are; HEIC becomes JPEG, which Obsidian can
    show; anything else (a web page shared on the phone) becomes a PDF.
    """
    sc = Shortcut(FILE_PICKER)
    sc.comment(GENERATED)
    sc.version_check()
    device = choose_vault(sc, vaults, home, icloud_on_mac)
    with sc.repeat_each(shortcut_input()) as item:
        sc.set_variable("url", sc.get_text(""))
        name = sc.compose(sc.replace(item_name(item), UNSAFE_NAME, "_"), "name")
        # Upper or lower case alike: photos from the phone come as .HEIC.
        kind = sc.file_extension(item)
        kind = sc.replace(kind, r"^pdf$", "kind-pdf", case_sensitive=False)
        kind = sc.replace(kind, r"^(?:jpe?g|png|gif|webp|bmp|svg|avif)$", "kind-image", case_sensitive=False)
        kind = sc.replace(kind, r"^(?:heic|heif)$", "kind-heic", case_sensitive=False)

        def keep(file: dict, extension: dict, label: str, embed: str):
            sc.set_variable("file", file)
            sc.set_variable("extension", extension)
            sc.set_variable("prefix", sc.get_text(label))
            # "!" embeds an image under the task; a PDF gets a plain link.
            sc.set_variable("embed", sc.get_text(embed))

        with sc.if_(kind, IS, "kind-pdf") as is_pdf:
            keep(item, sc.get_text("pdf"), "PDF - ", "")
            is_pdf.otherwise()
            with sc.if_(kind, IS, "kind-image") as is_image:
                keep(item, sc.file_extension(item), "Image - ", "!")
                is_image.otherwise()
                with sc.if_(kind, IS, "kind-heic") as is_heic:
                    keep(sc.convert_to_jpeg(item), sc.get_text("jpg"), "Image - ", "!")
                    is_heic.otherwise()
                    keep(sc.make_pdf(item), sc.get_text("pdf"), "PDF - ", "")
                    # Where the PDF came from: a web page knows its address;
                    # a shared link is its own.
                    with sc.if_(sc.get_text("⟦", page_url(item), "⟧"), IS, EMPTY) as no_page:
                        found = sc.urls(item)
                        with sc.if_(found, HAS_VALUE):
                            sc.set_variable("url", sc.get_text("\n    ", sc.first_item(found)))
                        no_page.otherwise()
                        sc.set_variable("url", sc.get_text("\n    ", page_url(item)))

        def store(vault: Vault, root: str, inbox: str):
            # The file gets exactly the name the link will carry; see TIMESTAMP.
            sc.set_variable("stored", name)
            taken = sc.get_file(root, text(f"{inbox}/", name, ".", variable("extension")))
            with sc.if_(taken, HAS_VALUE):
                stamp = sc.replace(current_date(with_time=True), *TIMESTAMP)
                sc.set_variable("stored", sc.get_text(name, " ", stamp))
            sc.save_file(root, text(f"{inbox}/", variable("stored"), ".", variable("extension")),
                         variable("file"))
            # The link counts from the vault root, like every link in these
            # vaults: a relative one breaks as soon as the task is moved.
            entry = sc.get_text("- [ ] ", variable("prefix"), name, " ➕ ", current_date(),
                                "\n    ", variable("embed"), f"[[{vault.inbox}/", variable("stored"),
                                ".", variable("extension"), "]]", variable("url"))
            sc.append_file(root, f"{inbox}/_Inbox.md", entry)
            sc.append_variable("saved", sc.get_text(variable("stored"), ".", variable("extension")))

        for_each_location(sc, vaults, device, home, store)
    sc.notify(text(variable("saved"), " added to ", variable("vault"), " inbox."))
    return sc.workflow(FILE_INPUT, ["QuickActions", "ActionExtension"], surfaces=["Finder", "Services"],
                       no_input_error="Select or share a file to add.")


def wanted_shortcuts(vaults: list[Vault], home: Path = HOME, icloud_on_mac: bool = True):
    """(name, workflow, build) for every shortcut this Mac should have.

    The note picker only where the iPhone reaches one of the vaults: on the
    Mac, vault-note does its work. The work Mac, whose vaults are not on the
    phone and whose library is its own, gets the file picker alone.
    """
    wanted = []
    if any(phone_inbox(v, home) for v in vaults):
        wf, build = finalize(note_picker(vaults, home, icloud_on_mac))
        wanted.append((NOTE_PICKER, wf, build))
    wf, build = finalize(file_picker(vaults, home, icloud_on_mac))
    wanted.append((FILE_PICKER, wf, build))
    return wanted


