def run(*command, timeout=None, check=True) -> str:
    done = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    if check and done.returncode != 0:
        raise RuntimeError(f"{command[0]} failed: {done.stderr.strip() or done.stdout.strip()}")
    return done.stdout


def list_shortcuts() -> list[tuple[str, str]]:
    found = []
    for line in run("shortcuts", "list", "--show-identifiers").splitlines():
        match = re.match(r"^(.*) \(([0-9A-F-]{36})\)$", line)
        if match:
            found.append((match.group(1), match.group(2)))
    return found


def applescript_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def osascript(script: str) -> str:
    return run("osascript", "-e", script).strip()


def folder_of(shortcut_id: str) -> str:
    return osascript(f'tell application "Shortcuts Events"\n'
                     f'set f to folder of shortcut id {applescript_string(shortcut_id)}\n'
                     f'if f is missing value then return ""\n'
                     f'return name of f\nend tell')


def move_to_folder(shortcut_id: str, folder: str) -> None:
    osascript(f'tell application "Shortcuts Events"\n'
              f'if not (exists folder {applescript_string(folder)}) then '
              f'make new folder with properties {{name:{applescript_string(folder)}}}\n'
              f'set folder of shortcut id {applescript_string(shortcut_id)} to folder {applescript_string(folder)}\n'
              f'end tell')


def query_build(shortcut_id: str, token_file: Path) -> str | None:
    try:
        answer = run("shortcuts", "run", shortcut_id, "-i", str(token_file), timeout=QUERY_TIMEOUT, check=False)
    except subprocess.TimeoutExpired:
        return None
    return answer.strip() or None


def import_shortcut(wf: dict, name: str, workdir: Path) -> str:
    """Sign, open, wait for the click, and return the new shortcut's ID."""
    unsigned = workdir / "unsigned.shortcut"
    # Import names the shortcut after the file.
    signed = workdir / f"{name}.shortcut"
    unsigned.write_bytes(plistlib.dumps(wf, fmt=plistlib.FMT_BINARY))
    run("shortcuts", "sign", "--mode", "anyone", "--input", str(unsigned), "--output", str(signed))
    before = {sid for _, sid in list_shortcuts()}
    # -F: without restoring windows, so no editor reopens over the dialog.
    run("open", "-F", str(signed))
    print(f"  -> click 'Add Shortcut' (or 'Replace') in the Shortcuts dialog for '{name}'")
    deadline = time.time() + IMPORT_TIMEOUT
    pattern = re.compile(rf"^{re.escape(name)}( \d+)?$")
    while time.time() < deadline:
        for found_name, sid in list_shortcuts():
            if sid not in before and pattern.match(found_name):
                return sid
        time.sleep(2)
    raise RuntimeError(f"'{name}' was not imported within {IMPORT_TIMEOUT} s")


def pbs_status() -> tuple[dict, dict]:
    domain = plistlib.loads(run("defaults", "export", "pbs", "-").encode("utf-8"))
    return domain, domain.get("NSServicesStatus", {})


def write_pbs(domain: dict, status: dict) -> None:
    domain = {**domain, "NSServicesStatus": status}
    with tempfile.NamedTemporaryFile(suffix=".plist") as f:
        f.write(plistlib.dumps(domain))
        f.flush()
        run("defaults", "import", "pbs", f.name)
    run("/System/Library/CoreServices/pbs", "-update")


