def services_wanted(current: dict[str, str]) -> dict[str, dict]:
    """Shortcut ID -> the Services settings it needs, from name -> current ID.
    Only the file picker needs any: switched on for Finder."""
    return {sid: {"presentation_modes": dict(FINDER_MODES)}
            for name, sid in current.items() if name == FILE_PICKER}


def merge_services(status: dict, wanted: dict[str, dict], hidden: set[str], existing: set[str],
                   ours: set[str]):
    """New NSServicesStatus with the wanted settings applied, and the hidden
    shortcuts (parked copies) taken out of every menu and off every key.

    A wanted key is taken from wherever else it sits if that is a deleted
    shortcut or one of ours (a replaced copy still holds the key it had). Held
    by any other shortcut, it is left alone and reported. Everything else stays
    as it was: this dictionary holds every Services setting of the account.
    """
    result = {k: dict(v) if isinstance(v, dict) else v for k, v in status.items()}
    warnings = []
    keys = {s["key_equivalent"]: sid for sid, s in wanted.items() if "key_equivalent" in s}
    for entry, settings in status.items():
        match = SERVICE_ENTRY_RE.match(entry)
        if not match or not isinstance(settings, dict):
            continue
        holder, key = match.group(1), settings.get("key_equivalent")
        if key not in keys or keys[key] == holder:
            continue
        if holder in existing and holder not in ours:
            warnings.append(f"{key} is also bound to shortcut {holder}; left alone")
            continue
        rest = {k: v for k, v in settings.items() if k != "key_equivalent"}
        if rest:
            result[entry] = rest
        else:
            del result[entry]
    for holder in hidden:
        entry = SERVICE_ENTRY.format(id=holder)
        settings = {k: v for k, v in result.get(entry, {}).items() if k != "key_equivalent"}
        result[entry] = {**settings, "presentation_modes": dict(HIDDEN_MODES)}
    for holder, settings in wanted.items():
        entry = SERVICE_ENTRY.format(id=holder)
        result[entry] = {**result.get(entry, {}), **settings}
    return result, warnings


