# Building a shortcut
# --------------------------------------------------------------------------

# IDs inside a shortcut are derived from its name and position rather than
# random: the build ID is a hash of the whole shortcut, and has to come out the
# same on every Mac and every run for an unchanged definition.
NAMESPACE = uuid.UUID("5d0b7a4e-2b54-4f0e-9c1a-6f3b8f3c2a10")


def text(*parts) -> dict:
    """A text with variables in it. Shortcuts marks each variable with U+FFFC
    and records its position in UTF-16 units, which is why these texts are
    assembled here rather than written as templates."""
    s, attachments = "", {}
    for part in parts:
        if isinstance(part, str):
            s += part
        else:
            attachments[f"{{{len(s.encode('utf-16-le')) // 2}, 1}}"] = part
            s += "￼"
    return {"Value": {"string": s, "attachmentsByRange": attachments},
            "WFSerializationType": "WFTextTokenString"}


def attachment(ref: dict) -> dict:
    return {"Value": ref, "WFSerializationType": "WFTextTokenAttachment"}


def condition_input(ref: dict) -> dict:
    return {"Type": "Variable", "Variable": attachment(ref)}


def output(uid: str, name: str) -> dict:
    return {"OutputUUID": uid, "Type": "ActionOutput", "OutputName": name}


def variable(name: str) -> dict:
    return {"Type": "Variable", "VariableName": name}


def shortcut_input(as_text: bool = False) -> dict:
    ref = {"Type": "ExtensionInput"}
    if as_text:
        # Without the coercion an If cannot compare Shortcut Input with a text:
        # it accepts many types, and the editor leaves the value field empty.
        ref["Aggrandizements"] = [{"Type": "WFCoercionVariableAggrandizement",
                                   "CoercionItemClass": "WFStringContentItem"}]
    return ref


def iso_date(ref: dict, with_time: bool = False) -> dict:
    return {**ref, "Aggrandizements": [{
        "Type": "WFDateFormatVariableAggrandizement", "WFDateFormatStyle": "ISO 8601",
        "WFISO8601IncludeTime": with_time}]}


def current_date(with_time: bool = False) -> dict:
    return iso_date({"Type": "CurrentDate"}, with_time)


def decomposed(letter: str) -> str:
    """The letter as base plus combining mark, written as an ICU pattern."""
    base, mark = unicodedata.normalize("NFD", letter)
    return f"{base}\\u{ord(mark):04X}"


def item_name(ref: dict) -> dict:
    return {**ref, "Aggrandizements": [{"Type": "WFPropertyVariableAggrandizement",
                                        "PropertyName": "Name", "PropertyUserInfo": "WFItemName"}]}


def page_url(ref: dict) -> dict:
    """The address of a shared Safari web page; empty for anything else.
    "Get URLs from Input" finds nothing in a web page: the address is only in
    this property."""
    return {**ref, "Aggrandizements": [{"Type": "WFPropertyVariableAggrandizement",
                                        "PropertyName": "Page URL"}]}


class Branch:
    def __init__(self, shortcut: "Shortcut", group: str):
        self.shortcut, self.group = shortcut, group

    def otherwise(self):
        self.shortcut.add("is.workflow.actions.conditional", GroupingIdentifier=self.group,
                          WFControlFlowMode=1)


class Shortcut:
    """One shortcut under construction."""

    def __init__(self, name: str):
        self.name = name
        self.actions: list[dict] = []
        self._count = 0

    def uid(self) -> str:
        self._count += 1
        return str(uuid.uuid5(NAMESPACE, f"{self.name}/{self._count}")).upper()

    def add(self, identifier: str, **parameters) -> None:
        # Every step gets an ID, as the editor gives it one, not only those
        # whose result is used later: "Always Allow" for appending or saving
        # was never stored for steps without one, and asked again every run.
        parameters.setdefault("UUID", self.uid())
        self.actions.append({"WFWorkflowActionIdentifier": identifier,
                             "WFWorkflowActionParameters": parameters})

    def step(self, identifier: str, output_name: str, **parameters) -> dict:
        uid = self.uid()
        self.add(identifier, UUID=uid, **parameters)
        return output(uid, output_name)

    # -- control flow ------------------------------------------------------

    @contextmanager
    def if_(self, ref: dict, condition: int, value: str | None = None):
        group = self.uid()
        parameters = dict(GroupingIdentifier=group, WFControlFlowMode=0, WFCondition=condition,
                          WFInput=condition_input(ref))
        if value is not None:
            parameters["WFConditionalActionString"] = value
        self.add("is.workflow.actions.conditional", **parameters)
        yield Branch(self, group)
        self.add("is.workflow.actions.conditional", GroupingIdentifier=group, WFControlFlowMode=2)

    @contextmanager
    def repeat_count(self, ref: dict):
        group = self.uid()
        self.add("is.workflow.actions.repeat.count", GroupingIdentifier=group, WFControlFlowMode=0,
                 WFRepeatCount=attachment(ref))
        yield
        self.add("is.workflow.actions.repeat.count", GroupingIdentifier=group, WFControlFlowMode=2)

    @contextmanager
    def repeat_each(self, ref: dict):
        group = self.uid()
        self.add("is.workflow.actions.repeat.each", GroupingIdentifier=group, WFControlFlowMode=0,
                 WFInput=attachment(ref))
        yield variable("Repeat Item")
        self.add("is.workflow.actions.repeat.each", GroupingIdentifier=group, WFControlFlowMode=2)

    # -- steps -------------------------------------------------------------

    def comment(self, note: str) -> None:
        self.add("is.workflow.actions.comment", WFCommentActionText=note)

    def version_check(self) -> None:
        """Answer the installer's question for the build, and do nothing else.
        Shortcut Input is coerced to text, so this costs one comparison before
        the dialog and passes silently when there is no input."""
        with self.if_(shortcut_input(as_text=True), IS, TOKEN):
            self.output(text(BUILD_PLACEHOLDER))

    def output(self, value: dict) -> None:
        # "Do Nothing" where there is nowhere to output: the ⌘⌥, run via Services
        # must not paste anything back over the selection.
        self.add("is.workflow.actions.output", WFOutput=value, WFNoOutputSurfaceBehavior="Do Nothing")

    def ask(self, prompt: str, default: dict) -> dict:
        uid = self.uid()
        self.add("is.workflow.actions.ask", UUID=uid, WFAskActionPrompt=prompt, WFInputType="Text",
                 WFAskActionDefaultAnswer=default, CustomOutputName="Note")
        return output(uid, "Note")

    def replace(self, ref: dict, find: str, replacement, case_sensitive: bool = True) -> dict:
        parts = replacement if isinstance(replacement, tuple) else (replacement,)
        parts = tuple(current_date() if p is DATE else variable("due") if p is DUE else p for p in parts)
        return self.step("is.workflow.actions.text.replace", "Updated Text",
                         WFInput=text(ref), WFReplaceTextRegularExpression=True,
                         WFReplaceTextCaseSensitive=case_sensitive, WFReplaceTextFind=find,
                         WFReplaceTextReplace=text(*parts))

    def get_text(self, *parts) -> dict:
        return self.step("is.workflow.actions.gettext", "Text", WFTextActionText=text(*parts))

    def set_variable(self, name: str, ref: dict) -> None:
        self.add("is.workflow.actions.setvariable", WFVariableName=name, WFInput=attachment(ref))

    def append_variable(self, name: str, ref: dict) -> None:
        self.add("is.workflow.actions.appendvariable", WFVariableName=name, WFInput=attachment(ref))

    def device_model(self) -> dict:
        return self.step("is.workflow.actions.getdevicedetails", "Device Model",
                         WFDeviceDetail="Device Model")

    def get_file(self, root: str, path) -> dict:
        """Quietly look up a file below a root; path is a string or a text()."""
        return self.step("is.workflow.actions.documentpicker.open", "File", WFFile=root_folder(root),
                         WFGetFilePath=path, WFFileErrorIfNotFound=False, WFShowFilePicker=False)

    def append_file(self, root: str, path: str, ref: dict) -> None:
        self.add("is.workflow.actions.file.append", WFFile=root_folder(root), WFFilePath=path,
                 WFAppendFileWriteMode="Append", WFInput=text(ref))

    def save_file(self, root: str, path: dict, ref: dict) -> dict:
        # No overwrite: Shortcuts numbers a duplicate name, and the link is
        # built from the name the file actually got.
        return self.step("is.workflow.actions.documentpicker.save", "Saved File",
                         WFFolder=root_folder(root), WFInput=attachment(ref), WFAskWhereToSave=False,
                         WFSaveFileOverwrite=False, WFFileDestinationPath=path)

    def file_extension(self, ref: dict) -> dict:
        return self.step("is.workflow.actions.properties.files", "File Extension",
                         WFInput=attachment(ref), WFContentItemPropertyName="File Extension")

    def adjust_date(self, date: dict, days: int) -> dict:
        """date plus a fixed number of days. The date goes in as a text with
        the variable in it; passed as the bare variable, the result is empty."""
        return self.step("is.workflow.actions.adjustdate", "Adjusted Date", WFAdjustOperation="Add", WFDate=date,
                         WFDuration={"Value": {"Magnitude": days, "Unit": "days"},
                                     "WFSerializationType": "WFQuantityFieldValue"})

    def make_pdf(self, ref: dict) -> dict:
        return self.step("is.workflow.actions.makepdf", "PDF", WFInput=attachment(ref))

    def convert_to_jpeg(self, ref: dict) -> dict:
        return self.step("is.workflow.actions.image.convert", "Converted Image",
                         WFInput=attachment(ref), WFImageFormat="JPEG")

    def urls(self, ref: dict) -> dict:
        return self.step("is.workflow.actions.detect.link", "URLs", WFInput=attachment(ref))

    def first_item(self, ref: dict) -> dict:
        return self.step("is.workflow.actions.getitemfromlist", "Item from List",
                         WFInput=attachment(ref), WFItemSpecifier="First Item")

    def choose_from_list(self, ref: dict, prompt: str) -> dict:
        return self.step("is.workflow.actions.choosefromlist", "Chosen Item",
                         WFInput=attachment(ref), WFChooseFromListActionPrompt=prompt)

    def notify(self, body: dict) -> None:
        self.add("is.workflow.actions.notification", WFNotificationActionBody=body,
                 WFNotificationActionSound=False)

    def stop(self) -> None:
        self.add("is.workflow.actions.exit")

    # -- composite steps ---------------------------------------------------

    def compose(self, ref: dict, name: str) -> dict:
        """Set variable `name` to ref with its decomposed letters composed.
        The replacements run only if a combining mark is present at all, so
        the usual name costs one step."""
        self.set_variable(name, ref)
        with self.unless(ref, COMPOSED):
            composed = ref
            for letter in COMPOSABLE:
                composed = self.replace(composed, decomposed(letter), letter)
            self.set_variable(name, composed)
        return variable(name)

    @contextmanager
    def unless(self, ref: dict, pattern: tuple):
        """Run the body unless pattern turns ref into its marker (see EMPTY)."""
        with self.if_(self.replace(ref, *pattern), IS, pattern[1]) as found:
            found.otherwise()
            yield

    @contextmanager
    def unless_empty(self, ref: dict):
        """Run the body unless ref is an empty text, as a property of the
        wrong kind of item is (see EMPTY)."""
        with self.if_(self.get_text("⟦", ref, "⟧"), IS, EMPTY) as empty:
            empty.otherwise()
            yield

    def note(self, ref: dict, write) -> None:
        """Turn a dialog's text into an inbox task and hand it to write(entry).
        A dialog left empty gives no value at all; one holding only spaces or
        blank lines gives a text, and writes nothing either."""
        with self.if_(ref, HAS_VALUE):
            with self.unless(ref, BLANK):
                entry = self.replace(ref, *NOTE_PIPELINE[0])
                entry = self.due_date(entry)
                for find, replacement in NOTE_PIPELINE[1:]:
                    entry = self.replace(entry, find, replacement)
                write(entry)

    def due_date(self, ref: dict) -> dict:
        """Take a "+N" marker off the first line. Sets "due" to " 📅 <date>",
        or to nothing without a marker, and returns the text without it."""
        self.set_variable("entry", ref)
        self.set_variable("due", self.get_text(""))
        with self.if_(self.replace(ref, *DUE_FOUND), IS, FOUND_DUE):
            days = self.replace(ref, *DUE_DAYS)
            # Adjust Date counts 0 for a number of days taken from a variable,
            # however it is passed; a fixed 1 works, hence one day per round.
            # The start is a date rather than a text of one, which would be
            # read back in the device's own date format. Zero rounds: today.
            self.set_variable("date", self.adjust_date(text({"Type": "CurrentDate"}), 0))
            with self.repeat_count(days):
                self.set_variable("date", self.adjust_date(text(variable("date")), 1))
            self.set_variable("due", self.get_text(" 📅 ", iso_date(variable("date"))))
            self.set_variable("entry", self.replace(ref, *DUE_MARKER))
        return variable("entry")

    def workflow(self, inputs: list[str], types: list[str], surfaces: list[str] | None = None,
                 no_input_error: str | None = None) -> dict:
        wf = {
            "WFWorkflowClientVersion": CLIENT_VERSION,
            "WFWorkflowMinimumClientVersion": MIN_CLIENT_VERSION,
            "WFWorkflowMinimumClientVersionString": str(MIN_CLIENT_VERSION),
            "WFWorkflowIcon": ICON,
            "WFWorkflowActions": self.actions,
            "WFWorkflowInputContentItemClasses": inputs,
            "WFWorkflowTypes": types,
            # The version check is the only output; see Shortcut.output.
            "WFWorkflowOutputContentItemClasses": ["WFStringContentItem"],
            "WFWorkflowHasOutputFallback": False,
            "WFWorkflowHasShortcutInputVariables": True,
            # The hand-made predecessors carried setup questions pointing at
            # the wrong steps; a generated shortcut needs none.
            "WFWorkflowImportQuestions": [],
        }
        if surfaces:
            wf["WFQuickActionSurfaces"] = surfaces
        if no_input_error:
            wf["WFWorkflowNoInputBehavior"] = {"Name": "WFWorkflowNoInputBehaviorShowError",
                                               "Parameters": {"Error": no_input_error}}
        return wf


def finalize(wf: dict) -> tuple[dict, str]:
    """Stamp the build ID into the version check. The ID is a hash of the
    shortcut with the placeholder still in it, so the installer can compute
    it without building twice. JSON rather than plist output: its form does
    not depend on the Python version, and two Macs must agree on the hash."""
    canonical = json.dumps(wf, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    build = hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:12]

    def stamp(node):
        if isinstance(node, dict):
            return {k: stamp(v) for k, v in node.items()}
        if isinstance(node, list):
            return [stamp(v) for v in node]
        if isinstance(node, str):
            return node.replace(BUILD_PLACEHOLDER, build)
        return node

    return stamp(wf), build


